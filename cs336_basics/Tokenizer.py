import pickle
from pathlib import Path

import regex as re


PAT = re.compile(r"'(?:[sdmt]|ll|ve|re)| ?\p{L}+| ?\p{N}+| ?[^\s\p{L}\p{N}]+|\s+(?!\S)|\s+")


class Tokenizer:
    def __init__(self, vocab, merges, special_tokens=None):
        self.vocab = dict(vocab)
        self.merges = merges
        self.special_tokens = tuple(dict.fromkeys(special_tokens or ()))
        self.token_ids = {token: index for index, token in self.vocab.items()}
        self.merge_rank = {pair: rank for rank, pair in enumerate(merges)}
        self.special_ids = {}
        for token in self.special_tokens:
            token_bytes = token.encode("utf-8")
            if token_bytes not in self.token_ids:
                index = max(self.vocab, default=-1) + 1
                self.vocab[index] = token_bytes
                self.token_ids[token_bytes] = index
            self.special_ids[token] = self.token_ids[token_bytes]

        specials = sorted(self.special_tokens, key=len, reverse=True)
        self.special_pattern = re.compile("(" + "|".join(map(re.escape, specials)) + ")") if specials else None

    @classmethod
    def from_files(cls, vocab_filepath, merges_filepath, special_tokens=None):
        # Use only vocab/merge pickle files generated by a trusted BPE run.
        if Path(vocab_filepath).suffix == ".pkl" and Path(merges_filepath).suffix == ".pkl":
            with open(vocab_filepath, "rb") as vocab_file:
                vocab = pickle.load(vocab_file)
            with open(merges_filepath, "rb") as merges_file:
                merges = pickle.load(merges_file)
        else:
            with open(vocab_filepath, encoding="utf-8") as vocab_file:
                vocab = {}
                for line in vocab_file:
                    index, token = line.rstrip("\r\n").split("\t", 1)
                    vocab[int(index)] = token.encode("utf-8")
            with open(merges_filepath, encoding="utf-8") as merges_file:
                merges = []
                for line in merges_file:
                    left, right = line.rstrip("\r\n").split("\t", 1)
                    merges.append((left.encode("utf-8"), right.encode("utf-8")))
        return cls(vocab, merges, special_tokens)

    def _encode(self, text):
        parts = self.special_pattern.split(text) if self.special_pattern else (text,)
        for part in parts:
            if part in self.special_ids:
                yield self.special_ids[part]
                continue

            for match in PAT.finditer(part):
                word = tuple(bytes([byte]) for byte in match.group().encode("utf-8"))
                while len(word) > 1:
                    pair = min(
                        (pair for pair in zip(word, word[1:]) if pair in self.merge_rank),
                        key=self.merge_rank.__getitem__,
                        default=None,
                    )
                    if pair is None:
                        break

                    new_word = []
                    i = 0
                    while i < len(word):
                        if i + 1 < len(word) and (word[i], word[i + 1]) == pair:
                            new_word.append(b"".join(pair))
                            i += 2
                        else:
                            new_word.append(word[i])
                            i += 1
                    word = tuple(new_word)

                for token in word:
                    yield self.token_ids[token]

    def encode(self, text):
        return list(self._encode(text))

    def encode_iterable(self, iterable):
        for text in iterable:
            yield from self._encode(text)

    def decode(self, tokens):
        return b"".join(self.vocab[token] for token in tokens).decode("utf-8", errors="replace")
